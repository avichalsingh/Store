export const videos: VideoProduct[] = rawVideos.map((video) =>
  enrichVideo({ ...video, productType: "VIDEO" }),
);

export function getVideoBySlug(slug: string) {
  return videos.find((v) => v.slug === slug);
}

export function getVideoById(id: string) {
  return videos.find((v) => v.id === id);
}

export function getVideosByCharacter(characterId: string) {
  return videos.filter((v) => v.characterId === characterId);
}

export function getTrendingVideos(limit = 10) {
  return videos.filter((v) => v.isTrending).slice(0, limit);
}

export function getRelatedVideos(video: VideoProduct, limit = 4) {
  return videos
    .filter(
      (v) =>
        v.id !== video.id &&
        (v.characterId === video.characterId || v.category === video.category)
    )
    .slice(0, limit);
}
