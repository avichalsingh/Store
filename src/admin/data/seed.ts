function buildAssetFromProduct(p: AdminProduct): MediaAsset {
  const id = `media-${p.slug}`;

  // AI Image products must never seed as video stubs — that routes
  // preview generation through the video encoder and hangs forever.
  if (p.productType === "AI_IMAGE") {
    const url =
      p.media.thumbnail ||
      p.aiImageData?.images?.find((i) => i.isCover)?.url ||
      p.aiImageData?.images?.[0]?.url ||
      "";
    if (url) {
      return createImageAssetFromUrl(url, { id, name: p.name });
    }
  }

  const durationSeconds = parseDurationLabel(p.duration);
  const sizeBytes = parseSizeLabel(p.media.downloadFileSize);
  const fileName = p.media.downloadFileName || `${p.slug}-1080.mp4`;
  const thumbTs = Math.min(8.4, Math.max(1, durationSeconds * 0.35));

  return {
    id,
    name: p.name,
    originalFileName: fileName,
    type: "video",
    master: {
      url: "",
      fileName,
      sizeBytes,
      sizeLabel: p.media.downloadFileSize || "12.0 MB",
      resolution: p.resolution,
      duration: p.duration,
      durationSeconds,
      access: "protected",
    },
    preview: {
      // No fake public .mp4 — storefront only plays generated derivatives
      url: "",
      status: "uploaded",
      resolution: seedMediaSettings.previewResolution,
      quality: "optimized",
      watermarkApplied: false,
      access: "public",
    },
    thumbnail: {
      url: p.media.thumbnail,
      source: "frame",
      timestamp: thumbTs,
      timestampLabel: formatTimestamp(thumbTs),
    },
    processingStatus: "ready",
    processingSteps: {
      ...EMPTY_PROCESSING_STEPS,
      // Seed catalog has poster frames only — no durable master/preview blobs.
      // Cards show the poster until a real master is uploaded and preview encoded.
      uploadComplete: true,
      thumbnailReady: true,
    },
    watermarkMode: "global",
    previewQuality: "optimized",
    usedByProductIds: [p.id],
    previewPlayback: "none",
    hasLocalBlob: false,
    createdAt: p.createdAt,
    updatedAt: p.updatedAt,
  };
}

