function linkProductsToAssets(
  products: AdminProduct[],
  assets: MediaAsset[],
): AdminProduct[] {
  const bySlug = new Map(
    assets.filter((a) => a.id.startsWith("media-")).map((a) => [a.id, a]),
  );

  return products.map((p) => {
    const assetId = `media-${p.slug}`;
    const asset = bySlug.get(assetId);
    if (!asset) return p;
    // Never attach a video asset to an image product (or vice versa).
    if (p.productType === "AI_IMAGE" && asset.type !== "image") return p;
    if (p.productType !== "AI_IMAGE" && asset.type === "image") return p;
    return {
      ...p,
      mediaAssetId: asset.id,
      media: assetToProductMedia(asset),
      thumbnailMode: "frame" as const,
      watermarkMode: "global" as const,
      previewQuality: asset.previewQuality,
    };
  });
}

