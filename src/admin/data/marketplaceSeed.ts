function bundleProduct(
  partial: Parameters<typeof product>[0] & {
    included: Array<{ id: string; relId: string }>;
    compareAtTotalInr: number;
    compareAtTotalUsd: number;
  },
): AdminProduct {
  const { included, compareAtTotalInr, compareAtTotalUsd, ...rest } = partial;
  return product({
    ...rest,
    productType: "BUNDLE",
    relationships: included.map((item, i) => ({
      id: item.relId,
      relatedProductId: item.id,
      relationshipType: "INCLUDED_IN_BUNDLE" as const,
      sortOrder: i,
    })),
    bundleData: {
      includedProductIds: included.map((i) => i.id),
      compareAtTotalInr,
      compareAtTotalUsd,
    },
  });
}

