function padTags(tags: string[]): string[] {
  const next = [...tags];
  while (next.length < HASHTAGS_PER_SET) next.push("");
  return next.slice(0, HASHTAGS_PER_SET);
}

function packItems(
  items: Array<{ text: string; label?: string; tags?: string[] }>,
): CaptionPackItem[] {
  return items.map((item, i) => ({
    id: `item-${i + 1}`,
    caption: item.text,
    hashtags: padTags(item.tags ?? []),
    label: item.label ?? "",
    notes: "",
  }));
}

function hashtagItems(
  rows: Array<{ name: string; tags: string[]; description?: string }>,
): CaptionPackItem[] {
  return rows.map((s, i) => ({
    id: `item-${i + 1}`,
    caption: "",
    hashtags: padTags(s.tags),
    label: s.name,
    notes: s.description ?? "",
  }));
}

function imgs(prefix: string, urls: string[]) {
  return urls.map((url, i) => ({
    id: `${prefix}-${i + 1}`,
    url,
    previewUrl: url,
    fileName: `${prefix}-${i + 1}.png`,
    isCover: i === 0,
    sizeLabel: "2.4 MB",
  }));
}

function money(inrReg: number, inrCur: number, usdReg: number, usdCur: number) {
  return {
    INR: { regularPrice: inrReg, currentPrice: inrCur },
    USD: { regularPrice: usdReg, currentPrice: usdCur },
  };
}

